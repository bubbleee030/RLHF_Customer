#!/usr/bin/env bash
# Powered adversarial evaluation -- the central claim deserves more than 21 responses.
#
# Every conclusion about adversarial robustness in this project rests on the
# `redteam` track of the 163-prompt manifest: **18 prompts, 21 responses**. Three
# separate bare-PPO runs showed exactly zero gain there (J bare 0.1739 vs base
# 0.1739; I 0.2857 vs 0.2381), and that single track is what produced their
# safety_regression verdicts. At n=21 the Wilson interval is roughly +/-0.18, so
# a real effect of the size we care about is barely resolvable.
#
# This evaluation uses 80 stratified prompts x 2 seeds = 160 responses per variant,
# a 7.6x increase in power. Sources are the HELD-OUT val split: generated by
# Mistral-Large-3-675B, a model never used to produce training data or to judge,
# and verified disjoint from Run P's training pool, the 163-prompt manifest, and
# the CM's training pairs.
#
# Baselines CANNOT be copied here -- these are new prompts -- so all five arms are
# generated fresh. Slots:
#   ppo_raw    <- Run P served BARE   (prompt-matched; the number that matters)
#   ppo_policy <- Run P + zh policy   (composition test, deliberately mismatched)
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
RUN=ppo_output/runP_adversarial_20260831
OUT=results/redteam_heldout_runP_20260831
MANIFEST=configs/policy_eval/redteam_heldout_manifest_80.jsonl
POLICIES=configs/policy_eval/example_policy.jsonl
ZH=configs/policy_eval/compiled/system_prompt_zh.txt
BI=configs/policy_eval/compiled/system_prompt_bilingual.txt
ACTOR=/backup/model/costomer_model
RM_DIR=/backup/reward_output/run_reward_cs_within_20260803/best
CM_DIR=cost_output/cmE_augmented_fullft_20260829/best-loss
N=2
AD="$RUN/final/actor_adapter"

# Wait for BOTH the P and Q evaluations to finish so nothing contends for GPUs
# or hammers the judge endpoint in parallel.
echo "$(date -Is) waiting for the P and Q evaluations to complete"
for i in $(seq 1 480); do
  [ -d results/fiveway_runP_20260831/report ] && [ -d results/fiveway_runQ_20260831/report ] && break
  sleep 120
done
[ -d "$AD" ] || { echo "FATAL: missing $AD"; exit 1; }

mkdir -p "$OUT/responses"
cat > "$OUT/MANIFEST_NOTE.json" <<JSON
{
  "purpose": "Adequately powered test of the one claim the 163-prompt manifest cannot settle: does training on adversarial prompts improve adversarial robustness?",
  "prompts": 80, "seeds": 2, "responses_per_variant": 160,
  "compare_to": "the existing redteam track: 18 prompts / 21 responses",
  "source": "datasets/augment/prompts_val.jsonl -- Mistral-Large-3-675B, a generator never used for training data or judging",
  "disjointness_verified": ["Run P training pool", "fiveway_manifest_163", "CM training pairs"],
  "ppo_raw": "Run P served BARE (prompt-matched)",
  "ppo_policy": "Run P + zh policy prompt (composition test, mismatched by construction)"
}
JSON

pick_pair() {
  mapfile -t u < <(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits)
  [ "${u[0]:-9}" -lt 1000 ] && [ "${u[1]:-9}" -lt 1000 ] && { echo "0,1"; return 0; }
  [ "${u[2]:-9}" -lt 1000 ] && [ "${u[3]:-9}" -lt 1000 ] && { echo "2,3"; return 0; }
  return 1
}
while ! GPUS=$(pick_pair); do sleep 120; done
echo "$(date -Is) generating all five arms on GPUs $GPUS"
set -a; . /home/ubuntu/.nchc_env; set +a
export CUDA_VISIBLE_DEVICES="$GPUS"
export PPO_RAW_ADAPTER="$AD" PPO_POLICY_ADAPTER="$AD" OUT MANIFEST POLICIES ZH BI ACTOR RM_DIR CM_DIR N

bash run_exp_docker.sh 'pip install --quiet peft 2>/dev/null; set -e
for pair in "base_raw 0" "base_policy_zh 1"; do
  set -- $pair
  python3 -m scripts.policy_eval.generate_responses_fiveway --variant "$1" --manifest "$MANIFEST" \
    --compiled-zh "$ZH" --compiled-bilingual "$BI" --actor-model "$ACTOR" \
    --output "$OUT/responses/$1.jsonl" --device "cuda:$2" --n "$N" &
done; wait
for pair in "base_policy_bilingual 0" "ppo_raw 1"; do
  set -- $pair
  python3 -m scripts.policy_eval.generate_responses_fiveway --variant "$1" --manifest "$MANIFEST" \
    --compiled-zh "$ZH" --compiled-bilingual "$BI" --actor-model "$ACTOR" \
    --ppo-policy-prompt zh \
    --ppo-raw-adapter-dir "$PPO_RAW_ADAPTER" --ppo-policy-adapter-dir "$PPO_POLICY_ADAPTER" \
    --output "$OUT/responses/$1.jsonl" --device "cuda:$2" --n "$N" &
done; wait
python3 -m scripts.policy_eval.generate_responses_fiveway --variant ppo_policy --manifest "$MANIFEST" \
  --compiled-zh "$ZH" --compiled-bilingual "$BI" --actor-model "$ACTOR" --ppo-policy-prompt zh \
  --ppo-raw-adapter-dir "$PPO_RAW_ADAPTER" --ppo-policy-adapter-dir "$PPO_POLICY_ADAPTER" \
  --output "$OUT/responses/ppo_policy.jsonl" --device cuda:0 --n "$N"
R=("$OUT"/responses/base_raw.jsonl "$OUT"/responses/base_policy_zh.jsonl \
   "$OUT"/responses/base_policy_bilingual.jsonl "$OUT"/responses/ppo_raw.jsonl \
   "$OUT"/responses/ppo_policy.jsonl)
EXP=$(( $(wc -l < "$MANIFEST") * N * 5 ))
python3 -m scripts.policy_eval.score_responses --responses "${R[@]}" \
  --rm-dir "$RM_DIR" --cm-dir "$CM_DIR" --output "$OUT/scores.jsonl" \
  --rm-device cuda:0 --cm-device cuda:1 --expected "$EXP"
python3 -m scripts.policy_eval.judge_policy_fiveway --responses "${R[@]}" \
  --policies "$POLICIES" --output "$OUT/judges.jsonl" --initial-max-tokens 4800 \
  --expected-groups $(( $(wc -l < "$MANIFEST") * N ))
python3 -m scripts.policy_eval.aggregate_report_fiveway --manifest "$MANIFEST" \
  --responses "${R[@]}" --scores "$OUT/scores.jsonl" --judges "$OUT/judges.jsonl" \
  --output-dir "$OUT/report" --expected-prompts "$(wc -l < "$MANIFEST")" \
  --expected-responses "$EXP" --expected-scores "$EXP" \
  --expected-judges $(( $(wc -l < "$MANIFEST") * N * 2 ))
'
echo "$(date -Is) powered adversarial evaluation complete -> $OUT/report"
